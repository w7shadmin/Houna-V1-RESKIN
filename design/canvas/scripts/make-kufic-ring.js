// Bakes Profile's Kufic ring (canvas "Phase 6 — Profile: the Kufic ring") into constants/kuficRing.ts:
// هُنا · نتنفّس معًا, repeated round a circle in Amiri Bold, shaped by HarfBuzz (so the letters join
// as Arabic should) and set as one outline path, which react-native-svg draws the same on every
// platform (its textPath doesn't shape Arabic reliably). Needs harfbuzzjs, which isn't an app
// dependency: run it from a folder where it's installed, e.g.
//   npm i --prefix <tmp> harfbuzzjs@0.4 && NODE_PATH=<tmp>/node_modules node design/canvas/scripts/make-kufic-ring.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..', '..');
const FONT = path.join(ROOT, 'node_modules/@expo-google-fonts/amiri/700Bold/Amiri_700Bold.ttf');
const OUT = path.join(ROOT, 'constants/kuficRing.ts');
const PHRASE = 'هُنا · نتنفّس معًا · ';
const R = 88; // the baseline's radius
const PAD = 24; // room round it for the letters
const SIZE = 15; // font size, px (fitted to a whole number of phrases below)

(async () => {
  const hb = await require('harfbuzzjs');
  const blob = hb.createBlob(fs.readFileSync(FONT));
  const face = hb.createFace(blob, 0);
  const font = hb.createFont(face);
  const upem = face.upem;

  const shape = (text) => {
    const buffer = hb.createBuffer();
    buffer.addText(text);
    buffer.guessSegmentProperties();
    hb.shape(font, buffer);
    const glyphs = buffer.json();
    buffer.destroy();
    return glyphs;
  };
  const one = shape(PHRASE);
  const phraseWidth = one.reduce((a, g) => a + g.ax, 0);
  const circumference = 2 * Math.PI * R;
  // As many phrases as fit at about SIZE, then scaled to close the ring exactly.
  const count = Math.max(1, Math.round(circumference / ((phraseWidth / upem) * SIZE)));
  const glyphs = shape(PHRASE.repeat(count));
  const total = glyphs.reduce((a, g) => a + g.ax, 0);
  const s = circumference / total; // px per font unit
  const c = R + PAD;

  // Each glyph set upright on the circle at its pen position, clockwise from the top (visual order,
  // so the phrase reads right to left round the top, as on the canvas).
  let pen = 0;
  const parts = [];
  for (const g of glyphs) {
    const outline = font.glyphToPath(g.g);
    if (outline) {
      const theta = ((pen + g.dx) * s) / R;
      const out = [Math.sin(theta), -Math.cos(theta)];
      const tan = [Math.cos(theta), Math.sin(theta)];
      const ox = c + R * out[0], oy = c + R * out[1];
      const map = (x, y) => {
        const gx = x * s, gy = (y + g.dy) * s; // font y points up: outward
        return [ox + gx * tan[0] + gy * out[0], oy + gx * tan[1] + gy * out[1]];
      };
      parts.push(
        outline.replace(/([MLQCZ])([^MLQCZ]*)/g, (m, cmd, args) => {
          const nums = args.trim() ? args.trim().split(/[ ,]+/).map(Number) : [];
          const pts = [];
          for (let i = 0; i < nums.length; i += 2) pts.push(map(nums[i], nums[i + 1]).map((v) => v.toFixed(1)).join(' '));
          return cmd + pts.join(' ');
        }),
      );
    }
    pen += g.ax;
  }
  font.destroy();
  face.destroy();
  blob.destroy();

  const d = parts.join('');
  fs.writeFileSync(
    OUT,
    `// Generated by design/canvas/scripts/make-kufic-ring.js: don't edit by hand.\n` +
      `/** Profile's Kufic ring: ${JSON.stringify(PHRASE.trim())} ×${count} in Amiri Bold, shaped and set round a circle of radius ${R} in a ${2 * c}px box, as one outline. */\n` +
      `export const KUFIC_RING = { box: ${2 * c}, radius: ${R}, d: '${d}' };\n`,
  );
  console.log(`${count} phrases, ${glyphs.length} glyphs, ${(d.length / 1024).toFixed(1)} KB`);
})();
